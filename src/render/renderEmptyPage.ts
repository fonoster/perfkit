import type { Report } from "../schemas/index.js";
import { esc } from "./html.js";
import { pageStyles } from "./pageStyles.js";
import { renderFaviconLink } from "./renderFaviconLink.js";
import { FONTS } from "./renderRunPage.js";
import { renderLogo } from "./sections/renderLogo.js";

export const NO_RUNS_TEXT =
  "No published runs yet. When a run is in progress it appears here live.";

/**
 * The latest page of a site with no published runs: the nav's brand, the
 * project's eyebrow, title and lead, one line saying there are no runs yet,
 * and the footer, in the report page's styles. The app replaces it with the
 * live view when a run is in progress.
 */
export function renderEmptyPage(params: {
  project: Report["project"];
  perfkitVersion: string;
}): string {
  const { project, perfkitVersion } = params;
  const logo = renderLogo(project);
  const site = new URL(project.siteUrl);
  const methodology = `https://github.com/fonoster/perfkit/blob/v${perfkitVersion}/docs/report-page.md`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(`${project.name} benchmarks`)}</title>
${renderFaviconLink(project.faviconSvg)}<meta name="description" content="${esc(project.title)}">
<meta name="generator" content="perfkit ${esc(perfkitVersion)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="${esc(FONTS)}">
<style>
${pageStyles(project.accent)}
.no-runs { color: var(--text-muted); font-size: 15px; }
</style>
</head>
<body>
<header class="nav">
<div class="wrap nav-inner">
<div class="brand"><a class="brand-link" href="./">${logo}</a><span class="slash" aria-hidden="true">/</span><span class="product">Benchmarks</span></div>
</div>
</header>
<main>
<div class="hero">
<div class="wrap">
<p class="eyebrow">BENCHMARKS · ${esc(project.name.toUpperCase())}</p>
<h1 class="title">${esc(project.title)}</h1>
<p class="lead">${esc(project.lead)}</p>
<p class="no-runs" data-no-runs>${esc(NO_RUNS_TEXT)}</p>
</div>
</div>
</main>
<footer class="footer">
<div class="wrap footer-inner">
<div class="footer-brand">${logo}<p class="generated">Generated by perfkit ${esc(perfkitVersion)}</p></div>
<ul class="footer-links">
<li><a href="${esc(methodology)}">Methodology</a></li>
<li><a href="https://github.com/${esc(project.repo)}">GitHub</a></li>
<li><a href="${esc(site.origin)}/">${esc(site.host)}</a></li>
</ul>
</div>
</footer>
</body>
</html>
`;
}
