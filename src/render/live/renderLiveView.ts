import { esc } from "../html.js";
import { renderLogo } from "../sections/renderLogo.js";
import { renderLiveBanner } from "./renderLiveBanner.js";
import { renderLiveCapacity } from "./renderLiveCapacity.js";
import { renderLiveHeader } from "./renderLiveHeader.js";
import { renderLiveNav } from "./renderLiveNav.js";
import { renderLiveNumbers } from "./renderLiveNumbers.js";
import { renderLiveProgress } from "./renderLiveProgress.js";
import { renderLiveSoak } from "./renderLiveSoak.js";
import type { LiveViewContext, LiveViewParts } from "./types.js";

/**
 * The live view's parts: the nav (drawn once per run), and the banner,
 * main and footer, which the app replaces on every poll.
 */
export function renderLiveView(ctx: LiveViewContext): LiveViewParts {
  const { live } = ctx;
  const sections = live.benchmarks
    .map((benchmark, index) =>
      benchmark.state === "not-run"
        ? ""
        : benchmark.kind === "capacity"
          ? renderLiveCapacity(benchmark, index, ctx)
          : renderLiveSoak(benchmark, index, ctx)
    )
    .filter(Boolean)
    .join("\n");
  return {
    nav: renderLiveNav(ctx),
    banner: renderLiveBanner(ctx),
    main: [
      renderLiveHeader(ctx),
      renderLiveProgress(ctx),
      renderLiveNumbers(ctx),
      sections
    ].join("\n"),
    footer: `<footer class="footer">
<div class="wrap footer-inner">
<div class="footer-brand">${renderLogo(live.project)}<p class="generated">Generated by perfkit ${esc(ctx.perfkitVersion)} from live.json · schema ${esc(live.schema)} · preliminary</p></div>
</div>
</footer>`
  };
}
