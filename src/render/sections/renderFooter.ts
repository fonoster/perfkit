import { esc } from "../html.js";
import type { PageContext } from "../types.js";
import { renderLogo } from "./renderLogo.js";

/** Who generated the page, from what, and where to read how. */
export function renderFooter(ctx: PageContext): string {
  const { project } = ctx.report;
  const site = new URL(project.siteUrl);
  const methodology = `https://github.com/fonoster/perfkit/blob/v${ctx.perfkitVersion}/docs/report-page.md`;
  return `<footer class="footer">
<div class="wrap footer-inner">
<div class="footer-brand">${renderLogo(project)}<p class="generated">Generated by perfkit ${esc(ctx.perfkitVersion)} from report.json · schema ${esc(ctx.report.schema)}</p></div>
<ul class="footer-links">
<li><a href="${esc(methodology)}">Methodology</a></li>
<li><a href="https://github.com/${esc(project.repo)}">GitHub</a></li>
<li><a href="${esc(site.origin)}/">${esc(site.host)}</a></li>
</ul>
</div>
</footer>`;
}
